//! Correctly rounded binary32 math that gives the same bits on every platform.
//!
//! Rust lowers `f32::exp`, `ln`, `ln_1p`, `tanh`, `powf`, `sin` and `cos` to the C runtime's
//! functions, and those differ in their last bit between operating systems (UCRT against
//! glibc), between glibc versions, and between architectures. Everything the CPU backend
//! computes downstream of one of them inherits the difference. The functions here replace them:
//! each returns the binary32 nearest to the exact mathematical value (round to nearest, ties
//! to even), which is a single well-defined answer that any other correctly rounded library
//! agrees with, and which tests can take from a multi-precision reference rather than from this
//! code. See `docs/math.md`.
//!
//! # The determinism rule
//!
//! Inside this module only binary64/binary32 `+ - * /`, `sqrt`, comparisons, conversions, and
//! integer and bit operations are used: no `mul_add` (a fused multiply-add rounds once where
//! the separate operations round twice, and is a hardware instruction on some targets and a
//! library call on others), no standard-library or C-runtime math, nothing that depends on
//! target features, and no table computed at run time — every table is a literal in
//! `tables.rs`, generated by `scripts/gen_math_kat.py`. These operations are exactly specified
//! by IEEE 754 and Rust never contracts or reassociates them, so baseline x86-64, AVX-512 and
//! aarch64 builds give identical bits. The lint `tests/no_platform_libm.rs` keeps the rest of
//! the workspace off the platform functions.
//!
//! # Method
//!
//! CORE-MATH's design for binary32 (Sibidanov, Zimmermann and Glondu, "The CORE-MATH project",
//! ARITH 2022): evaluate in binary64 with a known error bound, accept the result when every
//! real number within that bound rounds to the same binary32, and otherwise take an accurate
//! path in double-double arithmetic (about 100 bits) whose result rounds correctly. For `exp`
//! and `tanh` an exhaustive test showed the check never changes a result, so those two round
//! their binary64 value directly (see `exp.rs`); `ln`, `ln_1p`, `sin` and `cos` need it on a
//! handful of inputs each and keep it. The code is
//! written for this module; each function's file states its algorithm, its sources and its
//! error bounds. Correct rounding of the unary functions is verified by an exhaustive test over
//! all `2^32` inputs against an independent reference (`tests/math.rs`, ignored by default);
//! `powf` is verified on known answers and a grid (its module doc says what is proven).
//!
//! # The helpers
//!
//! [`sigmoid`], [`silu`], [`gelu_tanh`] and [`softplus`] are NOT correctly rounded: they are the
//! expressions the CPU backend's call sites write, operation for operation, with the platform
//! function swapped for this module's. Their bits are as deterministic as the functions they
//! call, and a call site moving to one of them changes only where the platform function was
//! wrong.
//!
//! # NaN
//!
//! Every function here, scalar and slice, returns exactly [`NAN`] whenever its result is NaN:
//! for a NaN input (signalling, quiet, any payload, either sign) and for an invalid operation
//! (`ln(-1)`, `sin(inf)`, `silu(-inf)`'s `-inf/inf`). This is enforced explicitly, never left to
//! the hardware: x86 and AArch64 propagate payloads and choose the sign of a generated NaN
//! differently (x86 makes `0xffc00000`, AArch64's default NaN is `0x7fc00000`), so leaving it
//! to them would make NaN results differ in their bits across architectures.
//!
//! # Slices
//!
//! [`exp_slice`], [`exp_slice_to`], [`exp_sub_slice`], [`tanh_slice`], [`sigmoid_slice`],
//! [`silu_slice`] and [`gelu_tanh_slice`] apply the scalar functions to every element. Each
//! element goes through the SAME branch-free lane function the scalar version is (only
//! `+ - * /`, conversions, comparisons used as selects and table lookups by integer index), in
//! a loop the compiler vectorizes; there are no intrinsics and no `std::simd`. The loops are
//! compiled once per SIMD [`Tier`] and the widest the CPU supports is chosen at run time (see
//! `slices.rs`), so a baseline build still runs AVX2 or AVX-512 where the CPU has it. Each slice
//! function equals its scalar function element for element by construction, at every tier and
//! on every target; the tests check it on every binary32 input. `ln`, `ln_1p`, `sin`/`cos` and
//! `powf` have no slice form: they are not per-element hot paths (RoPE's frequencies depend only
//! on the op's shape: [`rope_freqs`]).

