//! Every kernel source assigned to the class `docs/plan/10-tunable-kernels.md` §1 sorts it into,
//! which decides how its hardware-shaped numbers can become parameters. `tuning::tests` fails
//! when a `.comp` file in `shaders/` is missing here (so a new shader cannot land unclassified)
//! and checks each assignment against what the source actually uses.

/// A kernel class (plan §1).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum ShaderClass {
    /// Already parameterized by a define, or width-agnostic.
    C1,
    /// Subgroup width only in local size, strides or per-subgroup arrays.
    C2,
    /// Shape baked into a layout shared with the host or with other kernels.
    C3,
    /// Cooperative matrix.
    C4,
    /// No subgroup operations: element-wise, gather and copy kernels (local size the only knob).
    C5a,
    /// No subgroup operations: shared-memory tree or tiled kernels (workgroup/tile a real knob).
    C5b,
}

