#!/usr/bin/env python3
"""Generate the constant tables of `infr_core::math` and its known-answer test data.

A development-time tool, never run by CI. It needs `mpmath` (install it into a virtual
environment, not the system Python). Every value it writes is computed with mpmath at several
hundred bits and rounded once, so neither output depends on any platform's math library.

    python -I scripts/gen_math_kat.py tables   # crates/infr-core/src/math/tables.rs
    python -I scripts/gen_math_kat.py kat [--hard FILE ...]
                                               # crates/infr-core/tests/data/math_kat.txt

`kat` writes, per function, range edges, special values, a deterministic spread of inputs, the
RoPE angles of two model geometries, and the hardest cases it can find: inputs whose exact
result lies closest to a rounding boundary of binary32. It scans its own candidates and also
reads candidate inputs from `--hard` files (one `fn hex [hex]` per line, as the exhaustive test
prints them); mpmath decides which are hardest, and the hardest are kept with their distance.

Both outputs are checked in. Regenerating `tables` must reproduce `tables.rs` byte for byte; a
diff means the script or mpmath changed, and is a bug to explain before committing.
"""

import argparse
import math
import os
import random
import struct
import sys
from fractions import Fraction

import mpmath
from mpmath import mp, mpf

mp.prec = 600

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLES = os.path.join(ROOT, "crates", "infr-core", "src", "math", "tables.rs")
KAT = os.path.join(ROOT, "crates", "infr-core", "tests", "data", "math_kat.txt")


# ── binary64 / binary32 helpers ──────────────────────────────────────────────────────────────


def f64_bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def f32_from_bits(b):
    return struct.unpack("<f", struct.pack("<I", b))[0]


def f32_bits(x):
    """Bits of a Python float that is EXACTLY a binary32 value (no rounding happens here)."""
    b = struct.unpack("<I", struct.pack("<f", x))[0]
    assert struct.unpack("<f", struct.pack("<I", b))[0] == x or x != x, x
    return b


def near_bits(x):
    """Bits of the binary32 nearest to a Python float (for hand-written edge constants)."""
    return struct.unpack("<I", struct.pack("<f", x))[0]


def to_f64(v):
    """The binary64 nearest to `v` (mpmath rounds to nearest)."""
    return float(mpf(v))


def round_bits(v, bits):
    """`v` rounded to `bits` significant bits, as an exact binary64."""
    v = mpf(v)
    if v == 0:
        return 0.0
    e = int(mpmath.floor(mpmath.log(abs(v), 2)))
    q = mpf(2) ** (e - bits + 1)
    r = mpmath.nint(v / q) * q
    f = float(r)
    assert mpf(f) == r
    return f


def dd(v):
    """`v` as an unevaluated sum hi + lo of two binary64 values."""
    hi = to_f64(v)
    lo = to_f64(mpf(v) - mpf(hi))
    return hi, lo


def f32_round(v):
    """(binary32 nearest to v, distance of v from the nearest rounding boundary in ulps).

    The distance is |t - (n + 1/2)| where t is v in units of the binary32 quantum at v: 0.5 for
    a value exactly on a representable number, 0 for an exact midpoint. Subnormals and overflow
    follow IEEE 754 round-to-nearest-even.
    """
    v = mpf(v)
    if v == 0:
        return 0.0, mpf(0.5)
    s = -1 if v < 0 else 1
    a = abs(v)
    e = int(mpmath.floor(mpmath.log(a, 2)))
    # log2 at 600 bits cannot misplace e except at an exact power of two, which it gets right.
    if mpf(2) ** e > a:
        e -= 1
    if mpf(2) ** (e + 1) <= a:
        e += 1
    q = mpf(2) ** (max(e, -126) - 23)
    t = a / q
    n = int(mpmath.floor(t))
    frac = t - n
    dist = abs(frac - mpf(0.5))
    if frac > 0.5 or (frac == 0.5 and n % 2 == 1):
        n += 1
    r = mpf(n) * q
    if r >= mpf(2) ** 128:
        return s * float("inf"), dist
    f = float(r)
    assert mpf(f) == r
    return s * f, dist


# ── tables.rs ────────────────────────────────────────────────────────────────────────────────


def hx(x):
    return f"b(0x{f64_bits(x):016x})"


def gen_tables():
    out = []
    w = out.append
    w("// GENERATED by scripts/gen_math_kat.py (`tables`) with mpmath; do not edit by hand.")
    w("// Regenerate with the script and commit the result; see docs/math.md.")
    w("//")
    w("// Every value is an exact binary64 bit pattern, so the tables mean the same thing on every")
    w("// compiler and target. `(hi, lo)` pairs are double-double values: hi + lo approximates the")
    w("// named quantity to about 106 bits.")
    w("")
    w("/// A binary64 from its bits.")
    w("const fn b(bits: u64) -> f64 {")
    w("    f64::from_bits(bits)")
    w("}")
    w("")
    ln2 = mpmath.log(2)

    # exp: 2^(j/64) and ln2/64 in three pieces. `k` stays below 2^14 in every caller, so the
    # 39-bit pieces make k*C1 and k*C2 exact.
    w("/// `2^(j/64)` for `j` in `0..64`, as `(hi, lo)`.")
    w("pub(super) const EXP2_J64: [(f64, f64); 64] = [")
    for j in range(64):
        hi, lo = dd(mpf(2) ** (mpf(j) / 64))
        w(f"    ({hx(hi)}, {hx(lo)}),")
    w("];")
    c = ln2 / 64
    c1 = round_bits(c, 39)
    c2 = round_bits(c - mpf(c1), 39)
    c3 = to_f64(c - mpf(c1) - mpf(c2))
    w("/// `ln(2)/64 = LN2_64_1 + LN2_64_2 + LN2_64_3`; the first two have 39 significant bits.")
    w(f"pub(super) const LN2_64_1: f64 = {hx(c1)};")
    w(f"pub(super) const LN2_64_2: f64 = {hx(c2)};")
    w(f"pub(super) const LN2_64_3: f64 = {hx(c3)};")
    w(f"/// `64/ln(2)`, rounded.")
    w(f"pub(super) const INV_LN2_64: f64 = {hx(to_f64(64 / ln2))};")
    w("/// `1/n!` for `n` in `0..=13`, as `(hi, lo)`.")
    w("pub(super) const INV_FACT: [(f64, f64); 14] = [")
    for n in range(14):
        hi, lo = dd(1 / mpmath.factorial(n))
        w(f"    ({hx(hi)}, {hx(lo)}),")
    w("];")

    # log: 128 intervals of the significand; reciprocals with 20 significant bits.
    w("/// Reciprocal of the centre of significand interval `i` (see `log.rs`), 20 significant")
    w("/// bits; exactly 1 for the two intervals that touch 1.")
    rs = []
    for i in range(128):
        lo_m = 1 + mpf(i) / 128
        hi_m = 1 + mpf(i + 1) / 128
        if i >= 64:
            lo_m, hi_m = lo_m / 2, hi_m / 2
        if i in (0, 127):
            r = 1.0
        else:
            r = round_bits(2 / (lo_m + hi_m), 20)
        zmax = max(abs(lo_m * r - 1), abs(hi_m * r - 1))
        assert zmax < mpf(1) / 126, (i, zmax)
        rs.append(r)
    w("pub(super) const LOG_R: [f64; 128] = [")
    for r in rs:
        w(f"    {hx(r)},")
    w("];")
    w("/// `-ln(LOG_R[i])`, as `(hi, lo)`.")
    w("pub(super) const LOG_L: [(f64, f64); 128] = [")
    for r in rs:
        hi, lo = dd(-mpmath.log(mpf(r)))
        w(f"    ({hx(hi)}, {hx(lo)}),")
    w("];")
    a = round_bits(ln2, 44)
    b = round_bits(ln2 - mpf(a), 44)
    cc = to_f64(ln2 - mpf(a) - mpf(b))
    w("/// `ln(2) = LN2_1 + LN2_2 + LN2_3`; the first two have 44 significant bits, so `e * LN2_1`")
    w("/// and `e * LN2_2` are exact for every binary exponent `e` the functions meet.")
    w(f"pub(super) const LN2_1: f64 = {hx(a)};")
    w(f"pub(super) const LN2_2: f64 = {hx(b)};")
    w(f"pub(super) const LN2_3: f64 = {hx(cc)};")
    w("/// `(-1)^(n+1)/n` for `n` in `0..=17` (index 0 unused), as `(hi, lo)`.")
    w("pub(super) const LOG1P_C: [(f64, f64); 18] = [")
    w("    (0.0, 0.0),")
    for n in range(1, 18):
        hi, lo = dd(mpf((-1) ** (n + 1)) / n)
        w(f"    ({hx(hi)}, {hx(lo)}),")
    w("];")

    # trig: sin/cos of j*pi/32, pi/32 in pieces, 2/pi bits.
    pi = mpmath.pi
    w("/// `sin(j*pi/32)` for `j` in `0..64`, as `(hi, lo)`.")
    w("pub(super) const SIN_J32: [(f64, f64); 64] = [")
    for j in range(64):
        hi, lo = dd(mpmath.sin(j * pi / 32))
        w(f"    ({hx(hi)}, {hx(lo)}),")
    w("];")
    w("/// `cos(j*pi/32)` for `j` in `0..64`, as `(hi, lo)`.")
    w("pub(super) const COS_J32: [(f64, f64); 64] = [")
    for j in range(64):
        hi, lo = dd(mpmath.cos(j * pi / 32))
        w(f"    ({hx(hi)}, {hx(lo)}),")
    w("];")
    p = pi / 32
    p1 = round_bits(p, 27)
    p2 = round_bits(p - mpf(p1), 27)
    p3 = to_f64(p - mpf(p1) - mpf(p2))
    w("/// `pi/32 = PI_32_1 + PI_32_2 + PI_32_3`; the first two have 27 significant bits, so")
    w("/// `k * PI_32_1` and `k * PI_32_2` are exact for `k < 2^26`.")
    w(f"pub(super) const PI_32_1: f64 = {hx(p1)};")
    w(f"pub(super) const PI_32_2: f64 = {hx(p2)};")
    w(f"pub(super) const PI_32_3: f64 = {hx(p3)};")
    hi, lo = dd(p)
    w(f"/// `pi/32` as `(hi, lo)`.")
    w(f"pub(super) const PI_32: (f64, f64) = ({hx(hi)}, {hx(lo)});")
    w(f"/// `32/pi`, rounded.")
    w(f"pub(super) const INV_PI_32: f64 = {hx(to_f64(32 / pi))};")
    nwords = 8
    big = int(mpmath.floor(2 / pi * mpf(2) ** (64 * nwords)))
    w("/// The binary expansion of `2/pi`: bit `i` (from 1) of `2/pi = 0.b1 b2 b3 ...` is bit")
    w("/// `63 - (i-1) % 64` of word `(i-1) / 64`.")
    w(f"pub(super) const TWO_OVER_PI: [u64; {nwords}] = [")
    for k in range(nwords):
        word = (big >> (64 * (nwords - 1 - k))) & (2**64 - 1)
        w(f"    0x{word:016x},")
    w("];")
    w("/// `(-1)^k/(2k+1)!` for `k` in `0..=8`, as `(hi, lo)`.")
    w("pub(super) const SIN_C: [(f64, f64); 9] = [")
    for k in range(9):
        hi, lo = dd(mpf((-1) ** k) / mpmath.factorial(2 * k + 1))
        w(f"    ({hx(hi)}, {hx(lo)}),")
    w("];")
    w("/// `(-1)^k/(2k)!` for `k` in `0..=9`, as `(hi, lo)`.")
    w("pub(super) const COS_C: [(f64, f64); 10] = [")
    for k in range(10):
        hi, lo = dd(mpf((-1) ** k) / mpmath.factorial(2 * k))
        w(f"    ({hx(hi)}, {hx(lo)}),")
    w("];")
    text = "\n".join(out) + "\n"
    os.makedirs(os.path.dirname(TABLES), exist_ok=True)
    with open(TABLES, "w", newline="\n") as f:
        f.write(text)
    print(f"wrote {TABLES}")


# ── known answers ────────────────────────────────────────────────────────────────────────────


def x_of(b):
    return mpf(f32_from_bits(b))


NAN = 0x7FC00000
INF = 0x7F800000
NEG_INF = 0xFF800000


def unary_special(fn, xb):
    """The result bits of `fn` at a special input (NaN, infinity, zero, outside the domain), or
    None for an ordinary input."""
    x = f32_from_bits(xb)
    if x != x:
        return NAN
    zero = x == 0
    if fn == "exp":
        return {INF: INF, NEG_INF: 0}.get(xb)
    if fn == "ln":
        if zero:
            return NEG_INF
        if x < 0:
            return NAN
        return INF if xb == INF else None
    if fn == "ln_1p":
        if zero:
            return xb
        if x == -1:
            return NEG_INF
        if x < -1:
            return NAN
        return INF if xb == INF else None
    if fn == "tanh":
        if zero:
            return xb
        return {INF: f32_bits(1.0), NEG_INF: f32_bits(-1.0)}.get(xb)
    if fn in ("sin", "cos"):
        if xb in (INF, NEG_INF):
            return NAN
        if zero:
            return xb if fn == "sin" else f32_bits(1.0)
        return None
    raise ValueError(fn)


def round_exact(q):
    """(bits of the binary32 nearest to the rational `q`, distance in ulps), ties to even, decided
    exactly with integer arithmetic."""
    if q == 0:
        return 0, mpf(0.5)
    sign = 0x80000000 if q < 0 else 0
    a = abs(q)
    e = a.numerator.bit_length() - a.denominator.bit_length()
    if Fraction(2) ** e > a:
        e -= 1
    if Fraction(2) ** (e + 1) <= a:
        e += 1
    quantum = Fraction(2) ** (max(e, -126) - 23)
    t = a / quantum
    n = t.numerator // t.denominator
    frac = t - n
    half = Fraction(1, 2)
    if frac > half or (frac == half and n % 2 == 1):
        n += 1
    dist = mpf(abs(frac - half).numerator) / abs(frac - half).denominator
    r = n * quantum
    if r >= Fraction(2) ** 128:
        return sign | INF, dist
    return sign | f32_bits(float(r)), dist


def iroot2k(v, k):
    """The integer r with r^(2^k) = v, or None."""
    for _ in range(k):
        r = math.isqrt(v)
        if r * r != v:
            return None
        v = r
    return v


def exact_power(xb, yb):
    """x^y as an exact Fraction when it is rational (an integer exponent of moderate size, or
    n/2^k with an exact 2^k-th root), else None. Exact results are where a rounding boundary can
    be hit exactly, which no finite precision can decide."""
    x = Fraction(f32_from_bits(xb))
    y = Fraction(f32_from_bits(yb))
    if x <= 0:
        return None
    k = y.denominator.bit_length() - 1  # y's denominator is 2^k
    n = y.numerator
    if abs(n) > 4096 or k > 12:
        return None
    xn = x ** n
    rn, rd = iroot2k(xn.numerator, k), iroot2k(xn.denominator, k)
    if rn is None or rd is None:
        return None
    return Fraction(rn, rd)


def evaluate(fn, x, y):
    """`fn` at the inputs, at the current mpmath precision."""
    if fn == "exp":
        return mpmath.exp(x)
    if fn == "ln":
        return mpmath.log(x)
    if fn == "ln_1p":
        return mpmath.log1p(x)
    if fn == "tanh":
        return mpmath.tanh(x)
    if fn == "sin":
        return mpmath.sin(x)
    if fn == "cos":
        return mpmath.cos(x)
    if fn == "powf":
        return mpmath.power(x, y)
    raise ValueError(fn)


def ref(fn, xb, yb=None):
    """(expected binary32 bits, distance to a rounding boundary in ulps) of `fn` at the inputs.

    An exact rational result (only `powf` has them) is rounded with integer arithmetic. Any
    other value is evaluated with mpmath at rising precision until it lies clearly on one side
    of every rounding boundary: accepted only when its distance from the nearest boundary
    exceeds the evaluation's own error by a wide margin, so noise cannot decide a near-tie."""
    if yb is None:
        sp = unary_special(fn, xb)
        if sp is not None:
            return sp, mpf(0.5)
    if fn == "powf":
        ex = exact_power(xb, yb)
        if ex is not None:
            return round_exact(ex)
    for prec in (600, 1200, 2400, 4800):
        with mp.workprec(prec):
            x = x_of(xb)
            y = x_of(yb) if yb is not None else None
            r, dist = f32_round(evaluate(fn, x, y))
            if dist > mpf(2) ** -(prec - 100):
                return f32_bits(r), +dist
    raise RuntimeError(f"{fn} {xb:08x} {yb}: undecided at 4800 bits")


def spread(rng, lo, hi, n, both_signs=False):
    """`n` binary32 bit patterns uniform in BIT space between two positive values."""
    a, b = near_bits(lo), near_bits(hi)
    out = [rng.randrange(a, b + 1) for _ in range(n)]
    if both_signs:
        out = [v | (0x80000000 if rng.random() < 0.5 else 0) for v in out]
    return out


def edges(*vals):
    """Each value and its two binary32 neighbours."""
    out = []
    for v in vals:
        b = near_bits(v)
        for d in (-2, -1, 0, 1, 2):
            c = (b & 0x7FFFFFFF) + d
            if 0 <= c < 0x7F800000:
                out.append(c | (b & 0x80000000))
    return out


SUBNORMALS = [1, 2, 3, 0x7FFFFF, 0x400000, 0x800000]
SPECIAL = [0x00000000, 0x80000000, 0x7F800000, 0xFF800000, 0x7FC00000, 0x3F800000, 0xBF800000]


def rope_angles(theta, rope_dim, positions):
    """f32 angles `pos * theta^(-2p/rd)` with every step rounded to binary32 correctly."""
    out = []
    for pos in positions:
        for p in range(rope_dim // 2):
            e, _ = f32_round(mpf(-2 * p) / rope_dim)
            inv, _ = f32_round(mpmath.power(mpf(theta), mpf(e)))
            a, _ = f32_round(mpf(pos) * mpf(inv))
            out.append(f32_bits(a))
    return out


def unary_inputs(fn, rng):
    xs = list(SPECIAL) + SUBNORMALS + [v | 0x80000000 for v in SUBNORMALS]
    if fn == "exp":
        xs += edges(88.72283, 88.7228394, 89.0, -87.33654, -103.27893, -103.97208, -104.0, 1.0)
        xs += spread(rng, 1e-30, 104.0, 1500, both_signs=True)
        xs += spread(rng, 1e-3, 30.0, 400)  # softmax: exp of negative values
        xs = xs[:-400] + [b | 0x80000000 for b in xs[-400:]]
    elif fn == "ln":
        xs += edges(1.0, 2.0, 0.5, 1.5, 0.75)
        xs += [f32_bits(1.0) + d for d in range(-40, 41)]
        xs += spread(rng, 1e-45, 3.4e38, 1500)
        xs += spread(rng, 0.9, 1.1, 300)
    elif fn == "ln_1p":
        xs += edges(-0.5, -0.99999994, 1.0, 2**-8, -(2**-8), 2**-7, 2**24, 2**53)
        xs += spread(rng, 1e-40, 3.4e38, 1200)
        xs += spread(rng, 1e-40, 0.9999, 600)
        xs = xs[:-600] + [b | 0x80000000 for b in xs[-600:]]
        xs += spread(rng, 1e-30, 1e-3, 300, both_signs=True)
    elif fn == "tanh":
        xs += edges(9.0, 9.0109, 9.1, 0.5, 1.0, 2**-12)
        xs += spread(rng, 1e-40, 12.0, 1500, both_signs=True)
        xs += spread(rng, 1e-30, 1e-3, 300, both_signs=True)
        xs += spread(rng, 12.0, 3.4e38, 50, both_signs=True)
    elif fn in ("sin", "cos"):
        xs += edges(3.1415927, 1.5707964, 6.2831855, 0.7853982, 2**22, 2**24)
        xs += spread(rng, 1e-40, 100.0, 900, both_signs=True)
        xs += spread(rng, 1e-30, 1e-3, 200, both_signs=True)
        xs += spread(rng, 100.0, 2**22, 300, both_signs=True)
        xs += spread(rng, 2**22, 3.4e38, 400, both_signs=True)
        # RoPE: Qwen3 (theta 1e6, head dim 128) and a Llama-style (theta 5e5, rope dim 64).
        xs += rope_angles(1e6, 128, [1, 7, 48, 1000, 32767])
        xs += rope_angles(5e5, 64, [3, 512, 131071])
    else:
        raise ValueError(fn)
    seen = set()
    return [x for x in xs if not (x in seen or seen.add(x))]


def pow_inputs(rng):
    pairs = []
    f = f32_bits
    for x in [0.0, -0.0, 1.0, -1.0, 2.0, -2.0, 0.5, float("inf"), -float("inf"), float("nan")]:
        for y in [0.0, -0.0, 1.0, -1.0, 2.0, 3.0, -3.0, 0.5, 2.5, float("inf"), -float("inf"),
                  float("nan")]:
            pairs.append((f(x), f(y)))
    # Exact results and exact midpoints: 11^7 is a 25-bit odd number, 66049^1.5 = 257^3.
    for x, y in [(11.0, 7.0), (66049.0, 1.5), (2.0**-75, 2.0), (2.0**-16, 9.375), (3.0, 15.0),
                 (9.0, 0.5), (1.0 + 2**-12, 2.0), (-11.0, 7.0), (-3.0, 3.0), (2.0, 127.0),
                 (2.0, 128.0), (2.0, -149.0), (2.0, -150.0), (10.0, 38.0), (10.0, -45.0)]:
        pairs.append((f(x), f(y)))
    # RoPE: theta^(-2p/rd) for the bases models use.
    for theta in [10000.0, 500000.0, 1000000.0, 10000000.0, 150000.0]:
        for rd in [64, 128, 96, 80]:
            for p in range(0, rd // 2, 3):
                e, _ = f32_round(mpf(-2 * p) / rd)
                pairs.append((f(theta), f32_bits(e)))
    # A spread of positive bases and moderate exponents.
    for _ in range(1200):
        x = rng.randrange(near_bits(1e-6), near_bits(1e6))
        y = rng.randrange(0, near_bits(30.0)) | (0x80000000 if rng.random() < 0.5 else 0)
        pairs.append((x, y))
    # Negative bases with integer exponents.
    for _ in range(200):
        x = rng.randrange(near_bits(0.01), near_bits(100.0)) | 0x80000000
        y = f(float(rng.randrange(-20, 21)))
        pairs.append((x, y))
    return pairs


def read_hard(paths):
    """Candidate inputs from `--hard` files: `fn xhex [yhex]` per line."""
    cand = {}
    for p in paths:
        with open(p) as fh:
            for line in fh:
                parts = line.split()
                if len(parts) < 2 or parts[0].startswith("#"):
                    continue
                key = tuple(int(h, 16) for h in parts[1:])
                cand.setdefault(parts[0], []).append(key)
    return cand


def scan_hard(fn, rng, n):
    """`n` random candidate inputs for the hardness scan."""
    if fn == "exp":
        return [(b,) for b in spread(rng, 1e-8, 88.7, n, both_signs=True)]
    if fn == "ln":
        return [(b,) for b in spread(rng, 1e-38, 3e38, n)]
    if fn == "ln_1p":
        return [(b,) for b in spread(rng, 1e-8, 1e30, n)]
    if fn == "tanh":
        return [(b,) for b in spread(rng, 1e-8, 9.0, n, both_signs=True)]
    if fn in ("sin", "cos"):
        return [(b,) for b in spread(rng, 1e-8, 1e30, n, both_signs=True)]
    raise ValueError(fn)


def gen_kat(hard_paths, scan):
    rng = random.Random(0x1F2E3D4C)
    cand = read_hard(hard_paths)
    lines = [
        "# GENERATED by scripts/gen_math_kat.py (`kat`) with mpmath; do not edit by hand.",
        "# fn x_bits [y_bits] expected_bits [# hard: distance from a rounding boundary in ulps]",
    ]
    for fn in ["exp", "ln", "ln_1p", "tanh", "sin", "cos"]:
        rows = [(x,) for x in unary_inputs(fn, rng)]
        hard = [c for c in cand.get(fn, [])] + scan_hard(fn, rng, scan)
        scored = []
        for c in hard:
            bits, dist = ref(fn, *c)
            scored.append((dist, c, bits))
        scored.sort()
        worst = scored[:40]
        hard_set = {c for _, c, _ in worst}
        for r in rows:
            if r in hard_set:
                continue
            bits, _ = ref(fn, *r)
            lines.append(f"{fn} {r[0]:08x} {bits:08x}")
        for dist, c, bits in worst:
            lines.append(f"{fn} {c[0]:08x} {bits:08x} # hard {mpmath.nstr(dist, 3)}")
        print(f"{fn}: {len(rows)} rows + {len(worst)} hard (hardest {mpmath.nstr(worst[0][0], 3)} ulp)")
    pairs = pow_inputs(rng) + cand.get("powf", [])
    seen = set()
    n = 0
    for x, y in pairs:
        if (x, y) in seen:
            continue
        seen.add((x, y))
        xv, yv = f32_from_bits(x), f32_from_bits(y)
        bits = pow_special(xv, yv)
        if bits is None:
            bits, dist = ref("powf", x, y)
            tag = f" # hard {mpmath.nstr(dist, 3)}" if dist < mpf(2) ** -20 else ""
        else:
            tag = ""
        lines.append(f"powf {x:08x} {y:08x} {bits:08x}{tag}")
        n += 1
    print(f"powf: {n} rows")
    os.makedirs(os.path.dirname(KAT), exist_ok=True)
    with open(KAT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {KAT}")


def is_odd_int(y):
    if y != y or abs(y) == float("inf"):
        return False
    return y == int(y) and abs(y) < 2**24 and int(y) % 2 == 1


def pow_special(x, y):
    """C99 `powf` special cases as bits, or None when the value is an ordinary power."""
    inf = float("inf")
    nan_bits = 0x7FC00000
    if y == 0:
        return f32_bits(1.0)
    if x == 1:
        return f32_bits(1.0)
    if x != x or y != y:
        return nan_bits
    if x == 0:
        neg = struct.pack("<f", x)[3] & 0x80
        if y < 0:
            return f32_bits(-inf if (neg and is_odd_int(y)) else inf)
        return f32_bits(-0.0 if (neg and is_odd_int(y)) else 0.0)
    if abs(y) == inf:
        if x == -1:
            return f32_bits(1.0)
        if (abs(x) < 1) == (y < 0):
            return f32_bits(inf)
        return f32_bits(0.0)
    if abs(x) == inf:
        if x > 0:
            return f32_bits(inf if y > 0 else 0.0)
        odd = is_odd_int(y)
        if y < 0:
            return f32_bits(-0.0 if odd else 0.0)
        return f32_bits(-inf if odd else inf)
    if x < 0 and y != int(y):  # y is finite here
        return nan_bits
    if x < 0:
        bits, _ = ref("powf", f32_bits(-x), f32_bits(y))
        return bits | 0x80000000 if is_odd_int(y) else bits
    return None


